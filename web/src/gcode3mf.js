//  zip 은 저장(압축 없음) 방식 — 프린터 · 프린터 라운지(SendService)가 읽는 자리: Metadata/plate_N.gcode (+ .md5), slice_info.config

const enc = new TextEncoder()

const CRC = (() => {
  const t = new Uint32Array(256)
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0 }
  return t
})()
export function crc32(u8) {
  let c = 0xFFFFFFFF
  for (let i = 0; i < u8.length; i++) c = CRC[(c ^ u8[i]) & 255] ^ (c >>> 8)
  return (c ^ 0xFFFFFFFF) >>> 0
}

/** MD5 (RFC 1321) → 16진 대문자 — Bambu Studio 가 plate_N.gcode.md5 에 적는 꼴 */
export function md5hex(u8) {
  const K = new Uint32Array(64), S = [7, 12, 17, 22, 5, 9, 14, 20, 4, 11, 16, 23, 6, 10, 15, 21]
  for (let i = 0; i < 64; i++) K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 4294967296) >>> 0
  const len = u8.length, n = ((len + 8 >>> 6) + 1) * 64, buf = new Uint8Array(n)
  buf.set(u8); buf[len] = 0x80
  const dv = new DataView(buf.buffer)
  dv.setUint32(n - 8, (len * 8) >>> 0, true); dv.setUint32(n - 4, Math.floor(len / 536870912) >>> 0, true)
  let a0 = 0x67452301, b0 = 0xefcdab89, c0 = 0x98badcfe, d0 = 0x10325476
  const M = new Uint32Array(16)
  for (let o = 0; o < n; o += 64) {
    for (let i = 0; i < 16; i++) M[i] = dv.getUint32(o + i * 4, true)
    let A = a0, B = b0, C = c0, D = d0
    for (let i = 0; i < 64; i++) {
      let F, g
      if (i < 16) { F = (B & C) | (~B & D); g = i } else if (i < 32) { F = (D & B) | (~D & C); g = (5 * i + 1) & 15 } else if (i < 48) { F = B ^ C ^ D; g = (3 * i + 5) & 15 } else { F = C ^ (B | ~D); g = (7 * i) & 15 }
      F = (F + A + K[i] + M[g]) >>> 0
      A = D; D = C; C = B
      const s = S[(i >> 4) * 4 + (i & 3)]
      B = (B + ((F << s) | (F >>> (32 - s)))) >>> 0
    }
    a0 = (a0 + A) >>> 0; b0 = (b0 + B) >>> 0; c0 = (c0 + C) >>> 0; d0 = (d0 + D) >>> 0
  }
  let out = ''
  for (const w of [a0, b0, c0, d0]) for (let i = 0; i < 4; i++) out += ((w >>> (i * 8)) & 255).toString(16).padStart(2, '0')
  return out.toUpperCase()
}

/** zip (저장 방식) — files: [[이름, Uint8Array]] → Blob */
export function zipStore(files) {
  const parts = [], central = []
  let off = 0
  for (const [name, data] of files) {
    const nb = enc.encode(name), crc = crc32(data)
    const lh = new DataView(new ArrayBuffer(30))
    lh.setUint32(0, 0x04034b50, true); lh.setUint16(4, 20, true); lh.setUint16(6, 0x0800, true); lh.setUint16(8, 0, true)
    lh.setUint16(10, 0, true); lh.setUint16(12, 0x21, true); lh.setUint32(14, crc, true); lh.setUint32(18, data.length, true); lh.setUint32(22, data.length, true)
    lh.setUint16(26, nb.length, true); lh.setUint16(28, 0, true)
    const cd = new DataView(new ArrayBuffer(46))
    cd.setUint32(0, 0x02014b50, true); cd.setUint16(4, 20, true); cd.setUint16(6, 20, true); cd.setUint16(8, 0x0800, true); cd.setUint16(10, 0, true)
    cd.setUint16(12, 0, true); cd.setUint16(14, 0x21, true); cd.setUint32(16, crc, true); cd.setUint32(20, data.length, true); cd.setUint32(24, data.length, true)
    cd.setUint16(28, nb.length, true); cd.setUint32(42, off, true)
    parts.push(lh.buffer, nb, data)
    central.push(cd.buffer, nb)
    off += 30 + nb.length + data.length
  }
  const cdSize = central.reduce((s, x) => s + (x.byteLength ?? x.length), 0)
  const end = new DataView(new ArrayBuffer(22))
  end.setUint32(0, 0x06054b50, true); end.setUint16(8, files.length, true); end.setUint16(10, files.length, true); end.setUint32(12, cdSize, true); end.setUint32(16, off, true)
  return new Blob([...parts, ...central, end.buffer], { type: 'model/3mf' })
}

const xml = (s) => String(s ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]))
const hms = (s) => { s = Math.max(0, Math.round(s)); const h = Math.floor(s / 3600), m = Math.floor(s % 3600 / 60), x = s % 60; return (h ? h + 'h ' : '') + (h || m ? m + 'm ' : '') + x + 's' }

/**
 * Bambu 머리말 — 프린터 화면이 남은 시간 · 층 수 · 쓴 양을 여기서 읽음 (엔진 G-code 에는 없어서 앞에 붙임)
 * @param {{seconds:number, layers:number, maxZ:number, tools:{mm:number, g:number, density:number}[]}} o
 */
export function bambuHeader(o) {
  const mm = o.tools.map((t) => t.mm.toFixed(2)).join(','), g = o.tools.map((t) => t.g.toFixed(2)).join(','), cm3 = o.tools.map((t) => (t.mm * Math.PI * 0.875 * 0.875 / 1000).toFixed(2)).join(',')
  return ['; HEADER_BLOCK_START', '; generated by 3DS Slicer (three-slicer, OrcaSlicer port) ' + new Date().toISOString().slice(0, 19).replace('T', ' '),
    '; model printing time: ' + hms(o.seconds) + '; total estimated time: ' + hms(o.seconds), '; total layer number: ' + o.layers,
    '; total filament length [mm] : ' + mm, '; total filament volume [cm^3] : ' + cm3, '; total filament weight [g] : ' + g,
    '; filament_density: ' + o.tools.map((t) => t.density).join(','), '; filament_diameter: ' + o.tools.map(() => '1.75').join(','),
    '; max_z_height: ' + o.maxZ.toFixed(2), '; HEADER_BLOCK_END', ''].join('\n')
}

/**
 * 판 하나짜리 .gcode.3mf
 * @param {{gcode:string, thumb?:Uint8Array, seconds:number, weight:number, tools:{type:string, color:string, mm:number, g:number}[], settings?:object, printer?:string}} o
 */
export function buildGcode3mf(o) {
  const g = enc.encode(o.gcode), md5 = md5hex(g)
  const files = [
    ['[Content_Types].xml', enc.encode('<?xml version="1.0" encoding="UTF-8"?>\n<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">\n <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>\n <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>\n <Default Extension="png" ContentType="image/png"/>\n <Default Extension="gcode" ContentType="text/x.gcode"/>\n</Types>\n')],
    ['_rels/.rels', enc.encode('<?xml version="1.0" encoding="UTF-8"?>\n<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">\n <Relationship Target="/3D/3dmodel.model" Id="rel-1" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>\n' + (o.thumb ? ' <Relationship Target="/Metadata/plate_1.png" Id="rel-2" Type="http://schemas.openxmlformats.org/package/2006/relationships/metadata/thumbnail"/>\n' : '') + '</Relationships>\n')],
    ['3D/3dmodel.model', enc.encode('<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">\n <metadata name="Application">3DS Slicer</metadata>\n <resources>\n </resources>\n <build>\n </build>\n</model>\n')],
    ['Metadata/plate_1.gcode', g],
    ['Metadata/plate_1.gcode.md5', enc.encode(md5)],
  ]
  if (o.thumb) files.push(['Metadata/plate_1.png', o.thumb])
  files.push(['Metadata/model_settings.config', enc.encode('<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <plate>\n    <metadata key="plater_id" value="1"/>\n    <metadata key="plater_name" value=""/>\n    <metadata key="locked" value="false"/>\n    <metadata key="gcode_file" value="Metadata/plate_1.gcode"/>\n' + (o.thumb ? '    <metadata key="thumbnail_file" value="Metadata/plate_1.png"/>\n' : '') + '  </plate>\n</config>\n')])
  files.push(['Metadata/slice_info.config', enc.encode('<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <header>\n    <header_item key="X-BBL-Client-Type" value="slicer"/>\n    <header_item key="X-BBL-Client-Version" value="3DS Slicer"/>\n  </header>\n  <plate>\n    <metadata key="index" value="1"/>\n' +
    (o.printer ? '    <metadata key="printer_model_id" value=""/>\n' : '') + '    <metadata key="prediction" value="' + Math.round(o.seconds) + '"/>\n    <metadata key="weight" value="' + o.weight.toFixed(2) + '"/>\n    <metadata key="outside" value="false"/>\n    <metadata key="support_used" value="false"/>\n' +
    o.tools.map((t, i) => '    <filament id="' + (i + 1) + '" type="' + xml(t.type) + '" color="' + xml(t.color) + '" used_m="' + (t.mm / 1000).toFixed(2) + '" used_g="' + t.g.toFixed(2) + '"/>\n').join('') + '  </plate>\n</config>\n')])
  if (o.settings) files.push(['Metadata/project_settings.config', enc.encode(JSON.stringify(o.settings, null, 4) + '\n')])
  return zipStore(files)
}
